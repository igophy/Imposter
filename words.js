export const CATEGORIES = Object.freeze(["Blandet", ...Object.keys(WORD_BANK)]);

export function wordsFor(category) {
  if (category === "Blandet") return [...new Set(Object.values(WORD_BANK).flat())];
  return WORD_BANK[category] ? [...WORD_BANK[category]] : [];
}

export function drawWord(category, previous = [], random = Math.random) {
  const words = wordsFor(category);
  if (!words.length) throw new Error("Velg en gyldig kategori.");
  let used = Array.isArray(previous)
    ? [...new Set(previous.filter((word) => words.includes(word)))]
    : [];
  let available = words.filter((word) => !used.includes(word));
  if (!available.length) {
    // A new deck must not repeat the very last word of the previous deck.
    const last = used.at(-1);
    available = words.length > 1 ? words.filter((word) => word !== last) : words;
    used = [];
  }
  const word = available[Math.min(available.length - 1, Math.floor(random() * available.length))];
  return { word, used: [...used, word] };
}
